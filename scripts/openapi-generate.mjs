#!/usr/bin/env node
// OpenAPI is the contract (17 T6). Usage: node scripts/openapi-generate.mjs [generate|check|lint]
//   generate  writes packages/shared/generated/{api-types.ts,schemas.json}
//   check     regenerates in memory and fails if the committed files differ (drift)
//   lint      fails unless every operation is mapped to exactly one module in x-modules
// Tool choice: openapi-typescript for types (maintained, supports OpenAPI 3.1, no runtime code).
// JSON Schemas need no tool: OpenAPI 3.1 schemas already are JSON Schema 2020-12, so we only
// move components.schemas under $defs and rewrite the $refs.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import openapiTS, { astToString } from 'openapi-typescript';

const SPEC = 'packages/shared/openapi/openapi.yaml';
const OUT = 'packages/shared/generated';
const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];
const BANNER = '// Generated by scripts/openapi-generate.mjs from openapi.yaml. Do not edit.\n';

export function loadSpec(root) {
  return parse(readFileSync(join(root, SPEC), 'utf8'));
}

/** Returns problems: operations without a module, in several modules, or listed but missing. */
export function lintModules(doc) {
  const ops = new Set();
  for (const item of Object.values(doc.paths ?? {})) {
    for (const m of METHODS) if (item[m]) ops.add(item[m].operationId ?? `${m} (no operationId)`);
  }
  const owners = new Map();
  for (const [mod, def] of Object.entries(doc['x-modules'] ?? {})) {
    for (const op of def.operations ?? []) owners.set(op, [...(owners.get(op) ?? []), mod]);
  }
  const problems = [];
  for (const op of ops) {
    const mods = owners.get(op) ?? [];
    if (mods.length === 0)
      problems.push(`operation ${op} is not mapped to any module in x-modules`);
    if (mods.length > 1)
      problems.push(`operation ${op} is mapped to several modules: ${mods.join(', ')}`);
  }
  for (const op of owners.keys()) {
    if (!ops.has(op)) problems.push(`x-modules lists unknown operation ${op}`);
  }
  return problems;
}

const rewriteRefs = (v) =>
  JSON.parse(JSON.stringify(v).replaceAll('#/components/schemas/', '#/$defs/'));

/** Builds the generated files in memory: { relativePath: content }. */
export async function generate(root) {
  const doc = loadSpec(root);
  const types = astToString(await openapiTS(doc));
  const schemas = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $defs: rewriteRefs(doc.components?.schemas ?? {}),
  };
  return {
    [`${OUT}/api-types.ts`]: BANNER + types,
    [`${OUT}/schemas.json`]: JSON.stringify(schemas, null, 2) + '\n',
  };
}

/** Returns the generated files that are missing or differ from a fresh generation. */
export async function drift(root) {
  const bad = [];
  for (const [file, content] of Object.entries(await generate(root))) {
    let current = null;
    try {
      current = readFileSync(join(root, file), 'utf8');
    } catch {
      /* missing counts as drift */
    }
    if (current !== content) bad.push(file);
  }
  return bad;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const mode = process.argv[2] ?? 'generate';
  if (mode === 'generate') {
    mkdirSync(join(root, OUT), { recursive: true });
    for (const [file, content] of Object.entries(await generate(root)))
      writeFileSync(join(root, file), content);
    console.log('generated');
  } else if (mode === 'check') {
    const bad = await drift(root);
    bad.forEach((f) => console.error(`${f} is out of date`));
    if (bad.length) {
      console.error('Run "npm run openapi:generate" and commit the result.');
      process.exit(1);
    }
    console.log('openapi generated files are up to date');
  } else if (mode === 'lint') {
    const problems = lintModules(loadSpec(root));
    problems.forEach((p) => console.error(p));
    if (problems.length) process.exit(1);
    console.log('x-modules ok');
  } else {
    console.error('Usage: openapi-generate.mjs [generate|check|lint]');
    process.exit(2);
  }
}

/**
 * The app's icons: Material Symbols (fonts.google.com/icons), Rounded, weight 400, grade 0, the
 * 24 px optical size, from Iconify's per-icon data (`@iconify-icons/material-symbols`). Each icon
 * is its own module, so only the icons imported here ship. They are drawn by Iconify's offline
 * component, which never fetches anything (MileWage calls no third party).
 *
 * Sizes follow Material: 24 px standalone (the default here), 20 px in a button (button.tsx sets
 * it), 18 px in dense spots (small buttons, chips, badges). A size class (`size-5`) overrides it.
 * Outlined by default; `filled` draws the filled form where Material switches to it (the selected
 * navigation destination). Hidden from screen readers unless given a `label`; a button with only
 * an icon is named by its own `aria-label` instead.
 */
export type IconProps = Omit<
  SVGProps<SVGSVGElement>,
  'ref' | 'fill' | 'mode' | 'onLoad' | 'rotate' | 'flip' | 'inline'
> & {
  /** The filled form (a selected navigation item). Icons without one stay outlined. */
  filled?: boolean;
  /** Read out as an image with this name; otherwise the icon is decorative. */
  label?: string;
};

export type IconComponent = (props: IconProps) => ReactElement;

function symbol(outlined: IconifyIcon, solid?: IconifyIcon): IconComponent {
  return function MaterialSymbol({ filled = false, label, ...props }: IconProps) {
    return (
      <Icon
        icon={filled && solid ? solid : outlined}
        width={24}
        height={24}
        {...(label ? { role: 'img', 'aria-label': label, 'aria-hidden': false } : {})}
        {...props}
      />
    );
  };
}

